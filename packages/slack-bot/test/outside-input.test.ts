import { test } from 'node:test';
import assert from 'node:assert/strict';
import { isHarnessInjected, isOutsideInput, matchesSentPrompt, rememberSentPrompt, renderOutsideInput, SENT_PROMPTS_CAP } from '../src/outside-input';

test('prompts the bot sent are recognised verbatim, wrapped by the server, or echoed as one TTY line', () => {
  const sent = ['review PR 2013\nand the tests', 'y'];
  assert.ok(matchesSentPrompt('review PR 2013 ⏎ and the tests', sent));
  assert.ok(matchesSentPrompt('# Feedback\n\nreview PR 2013\nand the tests\n\n[SLACK THREAD]…', sent));
  assert.ok(matchesSentPrompt('Y', sent));
  assert.ok(!matchesSentPrompt('yes, and also fix the lint errors', sent), 'a short send never hides a longer prompt');
  assert.ok(!matchesSentPrompt('fix the lint errors', sent));
  assert.ok(!matchesSentPrompt('fix the lint errors', undefined));
});

test('harness-written user envelopes are never announced', () => {
  for (const s of [
    '<system-reminder>\nsomething\n</system-reminder>',
    '<command-name>/clear</command-name>',
    '<local-command-stdout>ok</local-command-stdout>',
    '<environment_context>\n<cwd>/x</cwd>\n</environment_context>',
    '<permissions instructions>\nfoo',
    '[Request interrupted by user for tool use]',
    'Caveat: the messages below were generated by the user while running local commands. …',
    '# AGENTS.md instructions for /srv/app\n\n<INSTRUCTIONS>\n# AGENTS.md',
    '<task-notification>\n<task-id>b3vgs1kh3</task-id>',
    '<subagent_notification>\n{"agent_path":"x"}',
    '</image>',
    '<image name=[Image #1]>',
    'This session is being continued from a previous conversation that ran out of context.',
  ]) assert.ok(isHarnessInjected(s), s);
  assert.ok(!isHarnessInjected('< 5 items left; finish them'));
  assert.ok(!isHarnessInjected('please add a <title> tag'));
  assert.ok(isOutsideInput('please add a <title> tag', ['start']));
  assert.ok(!isOutsideInput('   ', ['start']));
});

test('the announcement quotes the prompt, escapes markup and truncates very long text', () => {
  const r = renderOutsideInput('fix <App/>\nthen run tests');
  assert.equal(r, '👤 _User asked outside Slack:_\n> fix &lt;App/&gt;\n> then run tests');
  const long = renderOutsideInput('x'.repeat(2000));
  assert.ok(long.length < 1700 && /\+500 chars/.test(long), long);
});

test('remembered prompts are capped', () => {
  let list: string[] | undefined;
  for (let i = 0; i < SENT_PROMPTS_CAP + 5; i++) list = rememberSentPrompt(list, `p${i}`);
  assert.equal(list!.length, SENT_PROMPTS_CAP);
  assert.equal(list![0], 'p5');
});

test('Claude Code image-dimension notes are harness text, not outside input', () => {
  const note = '[Image: original 1206x2622, displayed at 920x2000. Multiply coordinates by 1.31 to map to original image.]';
  assert.ok(isHarnessInjected(note));
  assert.ok(!isOutsideInput(note, ['start']));
});
