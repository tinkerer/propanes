/** Prompts the operator typed somewhere other than Slack (the admin PTY, the
 * structured view's input bar, a follow-up queue) show up in the transcript
 * as user turns the bot never sent. Announcing them in the thread keeps the
 * agent's next replies attributable; prompts the bot itself sent are matched
 * against what it remembers sending, and harness-injected user envelopes
 * (system reminders, slash-command output, codex environment context) are
 * never mistaken for a person typing. */
import { escapeMrkdwn } from './format';

export const SENT_PROMPTS_CAP = 20;
const OUTSIDE_INPUT_MAX = 1500;
const MIN_PARTIAL_MATCH = 12;

/** Whitespace, line markers and case never distinguish prompts: the TTY echoes
 * a multi-line Slack message as one line with ⏎ markers, and the server wraps
 * a dispatched request in its own template. */
export function normalizePrompt(text: string): string {
  return text.replace(/⏎/g, ' ').replace(/\s+/g, ' ').trim().toLowerCase();
}

/** True when a transcript user turn is one the bot sent (verbatim, or the
 * bot's text embedded in the server's dispatch/resume wrapper). Short sends
 * such as `y` or `1` match only exactly, so they cannot hide a real prompt. */
export function matchesSentPrompt(content: string, sent: readonly string[] | undefined): boolean {
  if (!sent?.length) return false;
  const turn = normalizePrompt(content);
  if (!turn) return true; // nothing to announce
  for (const raw of sent) {
    const s = normalizePrompt(raw);
    if (!s) continue;
    if (s === turn) return true;
    if (s.length >= MIN_PARTIAL_MATCH && (turn.includes(s) || s.includes(turn))) return true;
  }
  return false;
}

const INJECTED_OPENERS = [
  // <system-reminder>, <command-name>, <local-command-stdout>, <task-notification>, <environment_context>,
  // <subagent_notification>, <turn_aborted>, <user_instructions>, <permissions instructions>, <image …>, </image>
  /^<\/?[a-z][\w-]*(\s[^>]*)?>/i,
  /^\[request interrupted by user/i,
  /^\[agent note\]/i,
  /^caveat: the messages below were generated by the user while running local commands/i,
  /^context compacted/i,
  /^\[image: original \d+x\d+/i, // Claude Code's dimensions note after reading an image
  /^this session is being continued from a previous conversation/i,
  /^# agents\.md instructions for /i, // codex injects the repo's AGENTS.md as the first user turn
];

/** A user envelope written by the harness rather than typed by a person. */
export function isHarnessInjected(content: string): boolean {
  const head = content.trimStart();
  return INJECTED_OPENERS.some((re) => re.test(head));
}

export function isOutsideInput(content: string, sent: readonly string[] | undefined): boolean {
  if (!content.trim()) return false;
  if (isHarnessInjected(content)) return false;
  return !matchesSentPrompt(content, sent);
}

export function renderOutsideInput(content: string): string {
  let text = content.trim();
  if (text.length > OUTSIDE_INPUT_MAX) text = `${text.slice(0, OUTSIDE_INPUT_MAX)}… (+${(text.length - OUTSIDE_INPUT_MAX).toLocaleString()} chars)`;
  const quoted = escapeMrkdwn(text).split('\n').map((l) => `> ${l}`).join('\n');
  return `👤 _User asked outside Slack:_\n${quoted}`;
}

export function rememberSentPrompt(list: string[] | undefined, text: string): string[] {
  const next = [...(list ?? []), text];
  return next.length > SENT_PROMPTS_CAP ? next.slice(-SENT_PROMPTS_CAP) : next;
}
